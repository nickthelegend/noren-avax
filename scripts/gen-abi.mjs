// Writes sdk/src/abi.ts from the Foundry build output (run `forge build` first).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pick = { norenCreditAbi: 'NorenCredit', norenMerchantsAbi: 'NorenMerchants', norenTokenAbi: 'NorenTestToken', encryptedErcAbi: 'EncryptedERC', registrarAbi: 'Registrar', norenSettlementAbi: 'NorenSettlement', norenGasStationAbi: 'NorenGasStation', norenStockOracleAbi: 'NorenStockOracle', norenStockDeskAbi: 'NorenStockDesk', norenStockCreditAbi: 'NorenStockCredit', norenStockStarterAbi: 'NorenStockStarter' };
let out = '// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\n';
for (const [name, c] of Object.entries(pick)) {
  const j = JSON.parse(readFileSync(join(root, 'contracts/out', `${c}.sol`, `${c}.json`), 'utf8'));
  out += `export const ${name} = ${JSON.stringify(j.abi)} as const;\n`;
}
writeFileSync(join(root, 'sdk/src/abi.ts'), out);
console.log('wrote sdk/src/abi.ts');
